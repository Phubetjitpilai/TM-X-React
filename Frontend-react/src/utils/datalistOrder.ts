/** เรียงตัวเลือกของ <datalist> ให้ตัวที่ "ตรงกว่า" ขึ้นก่อน
 *
 *  ── ปัญหาที่แก้ ─────────────────────────────────────────────────────────
 *  เบราว์เซอร์กรอง <datalist> ด้วยการหา **substring** (ไม่ใช่ prefix) แล้วแสดง
 *  ผลลัพธ์ **ตามลำดับที่ <option> เรียงอยู่ใน DOM** โดยไม่จัดอันดับให้เลย
 *
 *  ผลคือพิมพ์ "5x5" แล้วได้:
 *      3.5x5      ← ขึ้นก่อน เพราะข้อความมี "5x5" อยู่ข้างใน และอยู่ต้นลิสต์
 *      5x5        ← ตัวที่ต้องการจริง ๆ ไปอยู่ล่างสุด
 *
 *  แก้ไม่ได้ด้วย CSS และสั่งเบราว์เซอร์ให้เรียงใหม่ก็ไม่ได้ — ทางเดียวคือเรา
 *  เรียง <option> เองตามสิ่งที่ผู้ใช้พิมพ์อยู่ ณ ตอนนั้น
 *
 *  ── ลำดับความสำคัญ ─────────────────────────────────────────────────────
 *    0  ตรงเป๊ะ           "5x5"  →  5x5
 *    1  ขึ้นต้นด้วย        "5x"   →  5x5, 5x7
 *    2  มีอยู่ข้างใน       "5x5"  →  3.5x5
 *    3  ไม่ตรงเลย         (เบราว์เซอร์กรองทิ้งอยู่แล้ว เก็บไว้ท้ายสุด)
 *
 *  ⚠ ใช้ `sort` บนสำเนา (`[...options]`) เสมอ — `Array.prototype.sort` แก้
 *    อาร์เรย์เดิมในที่ ถ้าเผลอส่ง state array เข้าไปตรง ๆ จะกลายเป็นการแก้
 *    state นอก setState แล้ว React จะไม่รู้ว่ามีอะไรเปลี่ยน (แก้ยากมาก)
 *
 *  ⚠ เสถียร (stable) — ตัวที่คะแนนเท่ากันคงลำดับเดิมไว้ ไม่สลับมั่ว
 *    (`Array.prototype.sort` ของ JS รับประกัน stable ตั้งแต่ ES2019)
 */
export function orderForDatalist(options: string[], typed: string): string[] {
  const q = (typed ?? "").trim().toLowerCase();
  if (!q) return options;                       // ยังไม่ได้พิมพ์ = ไม่ต้องจัดอันดับ

  const rank = (o: string): number => {
    const s = o.toLowerCase();
    if (s === q) return 0;
    if (s.startsWith(q)) return 1;
    if (s.includes(q)) return 2;
    return 3;
  };

  return [...options].sort((a, b) => rank(a) - rank(b));
}
